def _uuid7_str() -> str:
    """Generate a UUID v7 string (timestamp-based, per RFC 9562)."""
    ts_ms = int(time.time_ns() // 1_000_000) & ((1 << 48) - 1)
    rand_a = secrets.randbits(12)
    rand_b = secrets.randbits(62)
    value = (
        (ts_ms << (4 + 12 + 2 + 62))
        | (0x7 << (12 + 2 + 62))
        | (rand_a << (2 + 62))
        | (0b10 << 62)
        | rand_b
    )
    return str(UUID(int=value))


def _ensure_asset_ids(assets: list[dict]) -> list[dict]:
    """Ensure every asset dict has an 'id' field. Generate UUID v7 if missing."""
    for asset in assets:
        if not asset.get("id"):
            asset["id"] = _uuid7_str()
    return assets


async def _ws_send(ws: WebSocket, event_type: str, payload: dict[str, Any] | None = None) -> None:
    """Send message to client with error handling"""
    try:
        import json
        data = {"type": event_type, "payload": payload or {}}
        await ws.send_text(json.dumps(data, default=str))
    except WebSocketDisconnect:
        return
    except RuntimeError as e:
        if "Unexpected ASGI message" in str(e) or "once a close message has been sent" in str(e):
            return
        raise


async def _ws_error(
    ws: WebSocket,
    message: str,
    code: str,
    *,
    session_id: Optional[str] = None,
    details: Any = None,
) -> None:
    """Send error message to client"""
    payload = ErrorPayload(message=message, code=code, details=details)
    await _ws_send(ws, "error", payload.model_dump())
    logger.warning(
        f"WS error sent: {code} - {message}",
        extra={"session_id": session_id, "code": code, "details": details}
    )


async def _build_agent_state(
    session: SessionState,
    chat_payload: ChatPayload,
    workshop_id: str = "assets",
) -> dict:
    """
    Build initial AgentState from SessionState + ChatPayload.

    Returns dict that will be passed to agent.ainvoke().
    """
    from langchain_core.messages import HumanMessage
    from workshops_ai.wizard.prompt_context import PromptContextBuilder

    # Get valid asset types from catalog (cached 5-min)
    builder = PromptContextBuilder(session_id=session.session_id)
    asset_types_data = await builder._get_cached_catalog(
        "asset_types",
        builder.provider.load_asset_type_catalog
    )
    valid_asset_types = [at["name"] for at in asset_types_data]

    # wizard_steps["assets"]["assets"] is the single source of truth for assets.
    # chat_payload.assets (from frontend) takes priority if present; otherwise read wizard_steps.
    if chat_payload.assets:
        assets_to_use = chat_payload.assets
        assets_source = "payload"
    else:
        assets_to_use = session.wizard_steps.get("assets", {}).get("assets", [])
        assets_source = "wizard_steps"
    logger.info(f"Assets for agent: {len(assets_to_use)} (source={assets_source})")

    # Read services from wizard_steps (generated by wizard, provides context for asset creation)
    services = session.wizard_steps.get("services", {}).get("services", [])
    if services:
        logger.info(f"Services for agent: {len(services)} from wizard_steps")

    # Convert all assets to dict format and ensure IDs
    all_assets = _ensure_asset_ids([
        a.model_dump() if hasattr(a, 'model_dump') else a
        for a in assets_to_use
    ])

    # Filter selected assets (user wants to actively work on these)
    selected_assets = [
        a.model_dump() if hasattr(a, 'model_dump') else a
        for a in assets_to_use
        if (getattr(a, 'selected', False) if hasattr(a, 'selected') else a.get('selected', False))
    ]

    # Convert recent_operations to dict format for AgentState
    recent_operations_dict = [
        {
            "turn": op.turn,
            "action": op.action,
            "assets": op.assets,
            "details": op.details,
            "timestamp": op.timestamp.isoformat(),
        }
        for op in session.recent_operations
    ]

    # Build initial state
    initial_state = {
        # New message
        "messages": [HumanMessage(content=chat_payload.message)],

        # From ChatPayload (fresh every message - source of truth)
        "input_assets": all_assets,  # ALL assets for context (avoid duplicates)
        "selected_assets": selected_assets,  # Only selected assets (user wants to work on)

        # From catalog cache
        "valid_asset_types": valid_asset_types,

        # From wizard steps (business services for context)
        "services": services,

        # From SessionState
        "recent_operations": recent_operations_dict,

        # Current request
        "user_message": chat_payload.message,
        "model": chat_payload.model,
        "session_id": session.session_id,
        "workshop_id": workshop_id,

        # Output (empty, will be filled by agent)
        "generated_assets": [],
        "deleted_asset_names": [],
        "tools_used": [],
        "needs_clarification": False,
        "clarification_question": None,
        "error": None,
    }

    return initial_state


async def handle_chat(
    ws: WebSocket,
    session: SessionState,
    chat_payload: ChatPayload,
    workshop_id: str = "assets",
) -> None:
    """Handle CHAT message"""
    if session.busy:
        await _ws_error(ws, "Agent is busy, please wait", "BUSY", session_id=session.session_id)
        return

    if _settings.ratelimit and _settings.ratelimit.enabled:
        rate_ok = await allow_ws("chat", session.session_id, _settings.ratelimit.per_minute)
        if not rate_ok:
            await _ws_error(
                ws,
                "Too many requests, please slow down",
                "RATE_LIMITED",
                session_id=session.session_id
            )
            return

    # Set busy flag
    from datetime import datetime, timezone
    session.busy = True
    session.busy_since = datetime.now(timezone.utc)
    await save_session(session)

    try:
        # If frontend sent assets in payload, persist to wizard_steps (single source of truth)
        if chat_payload.assets:
            assets_dicts = _ensure_asset_ids([
                a.model_dump() if hasattr(a, 'model_dump') else a
                for a in chat_payload.assets
            ])
            if "assets" not in session.wizard_steps:
                session.wizard_steps["assets"] = {}
            session.wizard_steps["assets"]["assets"] = assets_dicts
            await save_session(session)

        await _ws_send(ws, "progress", {"status": "running", "session_id": session.session_id})

        # Build initial state (_ensure_asset_ids assigns UUIDs to wizard_steps assets in-place)
        initial_state = await _build_agent_state(session, chat_payload, workshop_id=workshop_id)

        # Persist any newly assigned UUIDs to Redis (before agent reload overwrites them)
        if not chat_payload.assets:
            # Assets came from wizard_steps — _ensure_asset_ids mutated them in-place
            wiz_assets = session.wizard_steps.get("assets", {}).get("assets", [])
            if wiz_assets and any(a.get("id") for a in wiz_assets):
                await save_session(session)

        # Invoke agent with conversation history
        from workshops_ai.graph.assets.agent import invoke_asset_agent

        conversation_history = [
            {"role": msg.role, "content": msg.content}
            for msg in session.conversation
        ]
        input_assets = initial_state.get("input_assets", [])
        logger.info(f"Invoking agent: {len(input_assets)} assets, {len(conversation_history)} history msgs")

        # The payload's organization, else the one the wizard saved in the session
        organization = chat_payload.organization or session.organization
        task = asyncio.create_task(invoke_asset_agent(
            message=chat_payload.message,
            session_id=session.session_id,
            workshop_id=workshop_id,
            input_assets=initial_state.get("input_assets"),
            selected_assets=initial_state.get("selected_assets"),
            valid_asset_types=initial_state.get("valid_asset_types"),
            services=initial_state.get("services"),
            recent_operations=initial_state.get("recent_operations"),
            conversation_history=conversation_history,
            model=chat_payload.model,
            organization=organization.model_dump() if organization else None,
        ))
        _running_tasks[session.session_id] = task
        try:
            result = await task
        finally:
            _running_tasks.pop(session.session_id, None)

        # Extract tools used from agent messages
        from langchain_core.messages import ToolMessage
        tools_used = [
            msg.name for msg in result.get("messages", [])
            if isinstance(msg, ToolMessage) and hasattr(msg, "name")
        ]

        generated_assets = result.get("generated_assets", [])
        deleted_asset_names = result.get("deleted_asset_names", [])
        error = result.get("error")
        needs_clarification = result.get("needs_clarification", False)
        clarification_question = result.get("clarification_question")

        logger.info(
            f"Agent done: {len(generated_assets)} generated, {len(deleted_asset_names)} deleted, "
            f"tools={tools_used}, error={bool(error)}"
        )

        # Extract final AI message
        final_message = _extract_final_message(result)

        # Reload session to get updates from tools
        session = await get_session(session.session_id) or session

        # CRITICAL: Clear busy flag before saving conversation
        session.busy = False
        session.busy_since = None

        # Snapshot original assets BEFORE any modifications (for patch computation)
        original_assets_snapshot = list(session.wizard_steps.get("assets", {}).get("assets", []))

        # Compute patches BEFORE _ensure_asset_ids (which mutates dicts in-place)
        # so that new assets are correctly detected as "create" (no IDs yet)
        patches = compute_patches_auto(
            original_assets=original_assets_snapshot,
            generated_assets=generated_assets,
            deleted_asset_names=deleted_asset_names,
        )

        # Delete assets from wizard_steps if agent requested deletion
        if deleted_asset_names:
            existing_wiz = session.wizard_steps.get("assets", {}).get("assets", [])
            deleted_set = set(deleted_asset_names)
            remaining = [a for a in existing_wiz if a.get("name") not in deleted_set]
            removed_count = len(existing_wiz) - len(remaining)
            if "assets" not in session.wizard_steps:
                session.wizard_steps["assets"] = {}
            session.wizard_steps["assets"]["assets"] = remaining
            logger.info(f"Deleted {removed_count} assets from wizard_steps (remaining: {len(remaining)})")

        # Save generated assets to wizard_steps (single source of truth)
        if generated_assets:
            existing_wiz = session.wizard_steps.get("assets", {}).get("assets", [])

            # Split generated assets into updates (have ID matching existing) vs creates (new)
            existing_by_id = {a.get("id"): i for i, a in enumerate(existing_wiz) if a.get("id")}
            updates = []
            creates = []
            for asset_dict in generated_assets:
                aid = asset_dict.get("id")
                if aid and aid in existing_by_id:
                    updates.append(asset_dict)
                else:
                    creates.append(asset_dict)

            # Apply updates: replace existing assets in-place by ID
            if updates:
                for updated_asset in updates:
                    idx = existing_by_id[updated_asset["id"]]
                    existing_wiz[idx] = updated_asset
                logger.info(f"Updated {len(updates)} existing assets in wizard_steps")

            # Apply creates: add new assets (skip duplicates by name)
            if creates:
                existing_names = {a.get("name") for a in existing_wiz if a.get("name")}
                new_assets = [a for a in creates if a.get("name") and a.get("name") not in existing_names]
                if new_assets:
                    _ensure_asset_ids(new_assets)
                    existing_wiz = existing_wiz + new_assets
                    logger.info(f"Added {len(new_assets)} new assets to wizard_steps")

            if "assets" not in session.wizard_steps:
                session.wizard_steps["assets"] = {}
            session.wizard_steps["assets"]["assets"] = existing_wiz
            logger.info(f"Total assets in wizard_steps: {len(existing_wiz)}")

        # Record operation(s) in recent_operations (for agent context in next turn)
        if deleted_asset_names:
            add_recent_operation(
                session, action="deleted",
                assets=deleted_asset_names,
                details=f"{len(deleted_asset_names)} asset(s) deleted",
            )
        if generated_assets:
            from workshops_ai.session.utils import get_action_details_from_patches
            op_action, op_details = get_action_details_from_patches(patches)
            # If there were also deletes, this must be an update (not delete)
            if op_action == "deleted" and deleted_asset_names:
                op_action = "updated"
                op_details = "Updated after delete"
            add_recent_operation(
                session, action=op_action,
                assets=[a.get("name", "?") for a in generated_assets],
                details=op_details,
            )

        # Update session conversation history with assistant response
        from datetime import datetime, timezone
        now = datetime.now(timezone.utc)
        session.conversation.append(ConversationMessage(
            role="user",
            content=chat_payload.message,
            timestamp=now
        ))
        session.conversation.append(ConversationMessage(
            role="assistant",
            content=final_message,
            timestamp=now
        ))

        await save_session(session)
        logger.info(f"Session saved: {len(session.wizard_steps.get('assets', {}).get('assets', []))} assets, {len(session.conversation)} msgs")

        # Send response based on agent result
        if error:
            await _ws_error(
                ws,
                error,
                "AGENT_ERROR",
                session_id=session.session_id,
                details=error
            )
        else:
            # Determine action
            action = None
            if generated_assets or deleted_asset_names:
                has_creates = generated_assets and not any(
                    a.get("id") in {o.get("id") for o in original_assets_snapshot if o.get("id")}
                    for a in generated_assets if a.get("id")
                )
                has_updates = generated_assets and not has_creates
                has_deletes = bool(deleted_asset_names)

                if has_deletes and not generated_assets:
                    action = "deleted"
                elif has_updates:
                    action = "updated"
                elif has_creates:
                    action = "created"
                else:
                    action = "created"

            # Extract usage from agent result
            usage = _extract_usage(result)

            # Unified ui_response for all non-error cases
            response_message = clarification_question if needs_clarification else final_message
            payload = UIResponsePayload(
                message=response_message or "No response",
                patches=patches if patches else None,
                assets=generated_assets if generated_assets else None,
                tools_used=tools_used,
                usage=usage,
                action=action,
            )
            await _ws_send(ws, "ui_response", payload.model_dump())

        await _ws_send(ws, "progress", {"status": "done", "session_id": session.session_id})

    except asyncio.CancelledError:
        logger.info(f"Agent task cancelled for session {session.session_id}")
        # busy flag cleared by cancel handler
        return
    except asyncio.TimeoutError:
        await _ws_error(
            ws,
            f"Request timed out after {WS_TIMEOUT_SEC}s",
            "TIMEOUT",
            session_id=session.session_id
        )
    except WebSocketDisconnect:
        raise
    except Exception as e:
        logger.exception(f"Agent error for session {session.session_id}: {e}")
        await _ws_error(
            ws,
            f"Agent execution failed: {str(e)}",
            "AGENT_ERROR",
            session_id=session.session_id,
            details=str(e)
        )
    finally:
        # Ensure busy flag is cleared even on error/timeout
        # (happy path already clears it above)
        try:
            fresh_session = await get_session(session.session_id)
            if fresh_session and fresh_session.busy:
                fresh_session.busy = False
                fresh_session.busy_since = None
                await save_session(fresh_session)
                logger.warning(f"Cleared busy flag in finally block for session {session.session_id} (error/timeout path)")
        except Exception as e:
            logger.error(f"Failed to clear busy flag in finally for session {session.session_id}: {e}")


async def handle_sync_history(ws: WebSocket, session: SessionState) -> None:
    """Handle SYNC_HISTORY message"""
    payload = HistorySyncPayload(
        messages=session.conversation,
        total_messages=len(session.conversation),
        returned_messages=len(session.conversation)
    )
    await _ws_send(ws, "history_sync", payload.model_dump())
    logger.debug(
        f"History synced: {len(session.conversation)} messages",
        extra={"session_id": session.session_id}
    )


@router.websocket("/ws")
async def ws_endpoint(
    ws: WebSocket,
    session_id: str = Query(..., description="Session ID"),
    workshop_id: WorkshopId = Query(..., description="Agent type"),
) -> None:
    """WebSocket endpoint for AI agent communication"""

    auth_ok = await verify_ws_auth(ws)
    if not auth_ok:
        return

    await ws.accept()
    await WsHub.register(ws)

    rid = get_request_id() or "n/a"

    session = await get_session(session_id)
    if not session:
        session = SessionState(
            session_id=session_id,
        )
        await save_session(session)
        logger.info(
            f"Created new session",
            extra={
                "session_id": session_id,
                "workshop_id": workshop_id,
                "request_id": rid
            }
        )
    else:
        logger.info(
            f"Restored session",
            extra={
                "session_id": session_id,
                "workshop_id": workshop_id,
                "request_id": rid
            }
        )

    hello_payload = HelloPayload(
        session_id=session_id,
        workshop_id=workshop_id,
        message="Hello! I'm ready to help with your assets."
    )
    await _ws_send(ws, "hello", hello_payload.model_dump())

    try:
        while True:
            try:
                raw = await ws.receive_json()
            except WebSocketDisconnect:
                logger.info(f"Client disconnected", extra={"session_id": session_id})
                break
            except Exception as e:
                code = getattr(e, "code", None)
                if code in (1000, 1006):
                    logger.info(f"WS client disconnected ({code})", extra={"session_id": session_id})
                    break
                logger.warning(f"WS receive error: {e}", extra={"session_id": session_id})
                continue

            try:
                client_msg = ClientMessage.model_validate(raw)
            except ValidationError as ve:
                await _ws_error(
                    ws,
                    "Invalid message format",
                    "VALIDATION_ERROR",
                    session_id=session_id,
                    details=ve.errors()
                )
                continue
            except Exception as e:
                await _ws_error(
                    ws,
                    "Invalid message format",
                    "VALIDATION_ERROR",
                    session_id=session_id,
                    details=str(e)
                )
                continue

            if client_msg.type == "ping":
                await _ws_send(ws, "pong", {})
                continue

            if client_msg.type == "sync_history":
                await handle_sync_history(ws, session)
                continue

            if client_msg.type == "cancel":
                task = _running_tasks.pop(session_id, None)
                if task and not task.done():
                    task.cancel()
                session = await get_session(session_id) or session
                if session.busy:
                    session.busy = False
                    session.busy_since = None
                    await save_session(session)
                logger.info(f"Cancel received", extra={"session_id": session_id})
                continue

            if client_msg.type == "chat":
                if not client_msg.payload:
                    await _ws_error(
                        ws,
                        "Missing payload for chat message",
                        "VALIDATION_ERROR",
                        session_id=session_id
                    )
                    continue

                try:
                    chat_payload = ChatPayload.model_validate(client_msg.payload)
                except ValidationError as ve:
                    await _ws_error(
                        ws,
                        "Invalid chat payload",
                        "VALIDATION_ERROR",
                        session_id=session_id,
                        details=ve.errors()
                    )
                    continue

                # CRITICAL: Reload session from Redis before handling each message
                # to get the latest busy flag state
                session = await get_session(session_id) or session

                await handle_chat(ws, session, chat_payload, workshop_id=workshop_id)
                continue

    except WebSocketDisconnect:
        pass
    except Exception as e:
        logger.exception(f"Unexpected error in WebSocket handler: {e}", extra={"session_id": session_id})
    finally:
        # Cancel running task on disconnect
        task = _running_tasks.pop(session_id, None)
        if task and not task.done():
            task.cancel()
        try:
            await WsHub.unregister(ws)
        except Exception:
            pass
        logger.info(f"WebSocket closed", extra={"session_id": session_id})


def _extract_final_message(agent_result: dict) -> str:
    """
    Extract final assistant message from agent result.

    Args:
        agent_result: Result from agent.ainvoke()

    Returns:
        Final message content as string
    """
    try:
        messages = agent_result.get("messages", [])
        if not messages:
            return "No response from agent"

        last_msg = messages[-1]

        if isinstance(last_msg, dict):
            return last_msg.get("content", str(last_msg))
        elif hasattr(last_msg, "content"):
            return last_msg.content
        else:
            return str(last_msg)

    except Exception as e:
        logger.error(
            "Failed to extract final message",
            extra={"error": str(e)},
            exc_info=True
        )
        return "Error extracting response"


def _extract_usage(agent_result: dict) -> UsagePayload | None:
    """
    Sum token usage from all AIMessage objects in agent result.

    LangChain AIMessage.usage_metadata contains input_tokens, output_tokens, total_tokens.
    Falls back to response_metadata.token_usage (OpenAI-specific).
    """
    try:
        from langchain_core.messages import AIMessage

        prompt_tokens = 0
        completion_tokens = 0

        for msg in agent_result.get("messages", []):
            if not isinstance(msg, AIMessage):
                continue

            if msg.usage_metadata:
                prompt_tokens += msg.usage_metadata.get("input_tokens", 0)
                completion_tokens += msg.usage_metadata.get("output_tokens", 0)
            elif hasattr(msg, "response_metadata"):
                tu = msg.response_metadata.get("token_usage", {})
                prompt_tokens += tu.get("prompt_tokens", 0)
                completion_tokens += tu.get("completion_tokens", 0)

        if prompt_tokens == 0 and completion_tokens == 0:
            return None

        return UsagePayload(
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=prompt_tokens + completion_tokens,
        )

    except Exception as e:
        logger.warning(f"Failed to extract usage: {e}")
        return None
