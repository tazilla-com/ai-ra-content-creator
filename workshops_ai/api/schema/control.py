# api/models/schema/control.py
from typing import List, Optional
from uuid import UUID
from decimal import Decimal
from pydantic import BaseModel, Field

class ThreatCoverage(BaseModel):
    """
    Describes how a specific control contributes to mitigating a known threat.
    Used for evaluating the effectiveness of the control in AI-assisted control selection.
    """
    threatName: str = Field(
        ...,
        description="Referential name of the threat this control mitigates. Must match exactly.",
        json_schema_extra={"example": "Phishing attack"}
    )
    riskCoverage: Decimal = Field(
        ...,
        ge=0,
        le=100,
        max_digits=5,
        decimal_places=2,
        description="Percentage of risk coverage this control provides for the threat (0-100%).",
        json_schema_extra={"example": 75.5}
    )

class PlannedControl(BaseModel):
    """
    Represents a control from the system catalog, typically derived from security standards (e.g., ISO 27001).
    Can be referenced for risk mitigation, cost evaluation, or selected for implementation on specific assets.
    """
    id: Optional[UUID] = Field(
        None, description="UUID of the control if it already exists in the system catalog. Omit or set to null when creating a new catalog entry."
    )
    name: str = Field(
        ...,
        description="Unique name of the control in the catalog (e.g., 'Firewall', 'Identity Management'). Used as reference key; already localized.",
        json_schema_extra={"example": "Multi-Factor Authentication"}
    )
    description: Optional[str] = Field(
        None,
        description="Optional localized description of the control's function, purpose, or domain of application.",
        json_schema_extra={"example": "Require multiple forms of authentication to access systems"}
    )
    # Code list; always in english; get via API from backend
    category: Optional[str] = Field(
        None,
        description=(
            "Control category for classification. Must not be translated or localized. "
            "Typical values: 'Information security policies', 'Organization of information security', "
            "'Human resource security', 'Threat intelligence', 'Asset management', 'Access control', "
            "'Cryptography', 'Physical and environmental security', 'Business continuity management', "
            "'Operations security', 'Vulnerability Management', 'Communications security', "
            "'System acquisition, development and maintenance', 'Supplier relationships', "
            "'Compliance', 'Logging and monitoring', 'Other'."
        )
    )
    implementationCost: Optional[Decimal] = Field(
        None,
        ge=0,
        max_digits=10,
        decimal_places=2,
        description="Estimated one-time implementation cost in euros.",
        json_schema_extra={"example": 5000.00}
    )
    estimatedAnnualCost: Optional[Decimal] = Field(
        None,
        ge=0,
        max_digits=10,
        decimal_places=2,
        description="Estimated recurring annual operational cost of the control in euros.",
        json_schema_extra={"example": 1200.00}
    )
    threats: Optional[List[ThreatCoverage]] = Field(
        None, description="List of threats this control mitigates, including the risk coverage for each threat."
    )

class AssetControls(BaseModel):
    """
    Represents the list of controls proposed for implementation for a specific asset.
    Generated by AI to mitigate evaluated risks using optimal controls.
    """
    assetId: Optional[UUID] = Field(
        None,
        description="UUID of the asset, if available; used to match against existing asset records."
    )
    assetName: str = Field(
        ...,
        description="Unique name of the asset. Used as a reference if the ID is not yet assigned.",
        json_schema_extra={"example": "Customer Database"}
    )
    controls: List[PlannedControl] = Field(
        ...,
        description="List of planned controls selected for the asset, each with its coverage and cost information."
    )
