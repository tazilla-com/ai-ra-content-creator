"""
Asset creation, update, and listing tools.
"""

from __future__ import annotations

from typing import Annotated
from langchain_core.tools import tool, InjectedToolCallId
from langchain_core.messages import ToolMessage
from langgraph.prebuilt import InjectedState
from langgraph.types import Command
from pydantic import BaseModel, Field


class CreateAssetsInput(BaseModel):
    """Input for create_assets tool."""
    description: str = Field(
        ...,
        description=(
            "Detailed description of ALL assets to create — BOTH primary AND supporting. "
            "Include CIA values for primary assets. Mark supporting assets explicitly. "
            "MUST include everything in ONE call, never split primary/supporting."
        ),
        examples=[
            "1. Patient records database with PROTECTED confidentiality, HIGH integrity, HIGH availability. 2. Patient portal with PROTECTED confidentiality, MEDIUM integrity, HIGH availability. 3. Hospital servers as supporting server infrastructure. 4. Network switches as supporting network infrastructure.",
            "1. Customer database with PROTECTED confidentiality, HIGH integrity, HIGH availability. 2. Payment gateway with PROTECTED confidentiality, HIGH integrity, HIGH availability. 3. Data center servers as supporting server infrastructure. 4. Office staff as supporting personnel.",
        ]
    )


class UpdateAssetsInput(BaseModel):
    """Input for update_assets tool."""
    asset_names: list[str] = Field(
        ...,
        description="Names of assets to update. Must match existing asset names exactly.",
        min_length=1,
        examples=[
            ["Asset Name 1"],
            ["Asset Name 1", "Asset Name 2"],
            ["Asset Name 1", "Asset Name 2", "Asset Name 3"]
        ]
    )
    updates: dict = Field(
        ...,
        description=(
            "Fields to change. Can update: name, description, assetType, "
            "confidentiality, integrity, availability, isPrimary. "
            "Cannot update: id"
        ),
        examples=[
            {"confidentiality": "HIGH"},
            {"description": "Updated description", "availability": "HIGH"},
            {"confidentiality": "PROTECTED", "integrity": "HIGH", "availability": "MEDIUM"}
        ]
    )


VALID_UPDATE_FIELDS = {
    "name", "description", "assetType",
    "confidentiality", "integrity", "availability",
    "isPrimary"
}


@tool
def list_services(
    tool_call_id: Annotated[str, InjectedToolCallId],
    state: Annotated[dict, InjectedState]
) -> Command:
    """
    List the organization's business services from the wizard's first step: name, description and sector.

    Use them as context when proposing or creating assets. An empty list means the wizard has identified no
    services yet; that is no reason to stop.
    """
    services = state.get("services", [])

    if not services:
        content = "No services found. Services are generated by the wizard before the asset agent."
        return Command(
            update={
                "tools_used": ["list_services"],
                "messages": [ToolMessage(content=content, tool_call_id=tool_call_id)]
            }
        )

    services_summary = []
    for i, svc in enumerate(services, 1):
        name = svc.get("name", "Unnamed")
        desc = svc.get("description", "No description")
        sector = svc.get("sector", "Not set")
        services_summary.append(
            f"{i}. **{name}**\n"
            f"   - Description: {desc}\n"
            f"   - Sector: {sector}"
        )

    content = f"Found {len(services)} business service(s):\n\n" + "\n\n".join(services_summary)

    return Command(
        update={
            "tools_used": ["list_services"],
            "messages": [ToolMessage(content=content, tool_call_id=tool_call_id)]
        }
    )


@tool
def list_assets(
    tool_call_id: Annotated[str, InjectedToolCallId],
    state: Annotated[dict, InjectedState]
) -> Command:
    """
    List the assets that exist now: name, description, type, CIA values, primary or supporting, and whether the
    user has selected them.

    Call it when the user asks about their assets, and before changing or deleting assets, to copy their names
    exactly. Never guess an asset's name.
    """
    input_assets = state.get("input_assets", [])
    selected = state.get("selected_assets", [])
    selected_ids = {a.get("id") for a in selected if a.get("id")}
    selected_names = {a.get("name") for a in selected if a.get("name")}

    if not input_assets:
        content = "No assets found in the system. You can create new assets if needed."
        return Command(
            update={
                "tools_used": ["list_assets"],
                "messages": [ToolMessage(content=content, tool_call_id=tool_call_id)]
            }
        )

    # Format assets for display
    import json
    assets_summary = []
    for i, asset in enumerate(input_assets, 1):
        name = asset.get("name", "Unnamed")
        desc = asset.get("description", "No description")
        conf = asset.get("confidentiality", "Not set")
        integ = asset.get("integrity", "Not set")
        avail = asset.get("availability", "Not set")
        asset_type = asset.get("assetType", "Not set")
        is_primary = asset.get("isPrimary", False)
        is_selected = asset.get("id") in selected_ids or name in selected_names

        assets_summary.append(
            f"{i}. **{name}**\n"
            f"   - Description: {desc}\n"
            f"   - Type: {asset_type}\n"
            f"   - Confidentiality: {conf}\n"
            f"   - Integrity: {integ}\n"
            f"   - Availability: {avail}\n"
            f"   - Primary: {is_primary}\n"
            f"   - Selected by the user: {'yes' if is_selected else 'no'}"
        )

    content = f"Found {len(input_assets)} asset(s):\n\n" + "\n\n".join(assets_summary)

    return Command(
        update={
            "tools_used": ["list_assets"],
            "messages": [ToolMessage(content=content, tool_call_id=tool_call_id)]
        }
    )


@tool
def create_assets(
    description: str,
    tool_call_id: Annotated[str, InjectedToolCallId],
    state: Annotated[dict, InjectedState]
) -> Command:
    """
    Create assets from one description of all of them: primary and supporting assets in one call.

    Describe each asset as a numbered item: its name, what it holds or does, whether it is supporting, and for a
    primary asset its confidentiality, integrity and availability when they are known. Write the description in
    the user's language: the assets get their names and descriptions in it. The asset types are chosen from
    Tazilla's catalogue.

    Primary assets are information together with the business activity that uses it; they have CIA values.
    Supporting assets are what primary assets run on or depend on, such as systems, applications, servers,
    networks, devices, premises or staff; they have no CIA values.

    Example: "1. Customer orders and invoicing, PROTECTED confidentiality, HIGH integrity, HIGH availability.
    2. Order management system, supporting. 3. Office network, supporting."
    """
    from workshops_ai.graph.assets.tools.generator import generate_assets_with_structured_output

    organization = state.get("organization", {})
    existing_assets = state.get("input_assets", [])
    valid_types = state.get("valid_asset_types", [])
    services = state.get("services", [])

    if not valid_types:
        # LangGraph refuses a tool result without a ToolMessage for the call (ValueError)
        error_msg = "No valid asset types available. Cannot create assets."
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    result, rejected = generate_assets_with_structured_output(
        description=description,
        organization=organization,
        existing_assets=existing_assets,
        valid_types=valid_types,
        services=services,
        model=state.get("model"),
    )

    assets_dicts = [asset.model_dump() for asset in result.assets]

    # Return Command with ToolMessage (required for LangGraph). The agent reports what was created, so it
    # gets each asset's type and classification, not only its name
    lines = []
    for a in assets_dicts:
        if a.get("isPrimary"):
            lines.append(f"- {a['name']} ({a['assetType']}; primary; confidentiality {a['confidentiality']}, "
                         f"integrity {a['integrity']}, availability {a['availability']})")
        else:
            lines.append(f"- {a['name']} ({a['assetType']}; supporting)")
    content = f"Created {len(assets_dicts)} assets:\n" + "\n".join(lines)
    if rejected:
        content += "\nNot created, because their type is not in the catalogue: " + "; ".join(
            f"{a.name} (type {a.assetType!r})" for a in rejected)
    return Command(
        update={
            "generated_assets": assets_dicts,
            "tools_used": ["create_assets"],
            "messages": [
                ToolMessage(
                    content=content,
                    tool_call_id=tool_call_id
                )
            ]
        }
    )


@tool
def update_assets(
    asset_names: list[str],
    name: str | None = None,
    description: str | None = None,
    confidentiality: str | None = None,
    integrity: str | None = None,
    availability: str | None = None,
    assetType: str | None = None,
    isPrimary: bool | None = None,
    *,
    tool_call_id: Annotated[str, InjectedToolCallId],
    state: Annotated[dict, InjectedState]
) -> Command:
    """
    Change existing assets. Pass only the fields that change; the others stay as they are.

    asset_names: the names exactly as list_assets returns them; the same change applies to each of them.
    Fields: name, description, assetType (a type from Tazilla's catalogue), confidentiality (PUBLIC, INTERNAL,
    PROTECTED or STRICTLY_PROTECTED), integrity and availability (LOW, MEDIUM or HIGH), isPrimary. Supporting
    assets have no CIA values.

    A proposal that was never created is not an asset: create it with create_assets instead.
    """
    # Build updates dict from non-None parameters
    updates = {}
    if name is not None:
        updates["name"] = name
    if description is not None:
        updates["description"] = description
    if confidentiality is not None:
        updates["confidentiality"] = confidentiality
    if integrity is not None:
        updates["integrity"] = integrity
    if availability is not None:
        updates["availability"] = availability
    if assetType is not None:
        updates["assetType"] = assetType
    if isPrimary is not None:
        updates["isPrimary"] = isPrimary

    if not updates:
        error_msg = "No fields to update. Provide at least one field: name, description, confidentiality, integrity, availability, assetType, isPrimary"
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    input_assets = state.get("input_assets", [])
    valid_types = state.get("valid_asset_types", [])

    invalid_fields = set(updates.keys()) - VALID_UPDATE_FIELDS
    if invalid_fields:
        error_msg = f"Invalid update fields: {invalid_fields}. Valid: {VALID_UPDATE_FIELDS}"
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    if "assetType" in updates and updates["assetType"] not in valid_types:
        error_msg = f"Invalid assetType: {updates['assetType']}. Must be one of: {valid_types}"
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    cia_validation = {
        "confidentiality": {"PUBLIC", "INTERNAL", "PROTECTED", "STRICTLY_PROTECTED"},
        "integrity": {"LOW", "MEDIUM", "HIGH"},
        "availability": {"LOW", "MEDIUM", "HIGH"}
    }
    for field, valid_values in cia_validation.items():
        if field in updates and updates[field] is not None and updates[field] not in valid_values:
            error_msg = f"Invalid {field}: {updates[field]}. Must be one of: {valid_values} or None (for supporting assets)"
            return Command(
                update={
                    "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
                }
            )

    updated_assets = []
    not_found = []

    for asset_name in asset_names:
        asset = next((a for a in input_assets if a.get("name") == asset_name), None)

        if not asset:
            not_found.append(asset_name)
            continue

        updated_asset = {**asset, **updates}
        updated_assets.append(updated_asset)

    if not_found and not updated_assets:
        error_msg = f"No assets found with names: {not_found}. Check input_assets for correct names."
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    # Build success message
    success_msg = f"Updated {len(updated_assets)} assets"
    if not_found:
        success_msg += f". Warning: Some assets not found: {not_found}"

    return Command(
        update={
            "generated_assets": updated_assets,
            "tools_used": ["update_assets"],
            "messages": [
                ToolMessage(
                    content=success_msg,
                    tool_call_id=tool_call_id
                )
            ]
        }
    )


@tool
def delete_assets(
    asset_names: list[str],
    *,
    tool_call_id: Annotated[str, InjectedToolCallId],
    state: Annotated[dict, InjectedState]
) -> Command:
    """
    Delete existing assets, all in one call.

    asset_names: the names exactly as list_assets returns them. Names not found are reported; the others are
    deleted.
    """
    input_assets = state.get("input_assets", [])

    if not asset_names:
        error_msg = "No asset names provided. Specify which assets to delete."
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    deleted = []
    not_found = []

    for asset_name in asset_names:
        asset = next((a for a in input_assets if a.get("name") == asset_name), None)
        if asset:
            deleted.append(asset_name)
        else:
            not_found.append(asset_name)

    if not deleted:
        error_msg = f"No assets found with names: {not_found}. Use list_assets to check exact names."
        return Command(
            update={
                "messages": [ToolMessage(content=error_msg, tool_call_id=tool_call_id)]
            }
        )

    success_msg = f"Deleted {len(deleted)} asset(s): {', '.join(deleted)}"
    if not_found:
        success_msg += f". Warning: Not found: {', '.join(not_found)}"

    return Command(
        update={
            "deleted_asset_names": deleted,
            "tools_used": ["delete_assets"],
            "messages": [
                ToolMessage(
                    content=success_msg,
                    tool_call_id=tool_call_id
                )
            ]
        }
    )
